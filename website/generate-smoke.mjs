import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { convert } from './converter.mjs';
import { smokeCases, smokeDialects } from './smoke-cases.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const smokeOutput = path.join(root, 'build/converter-smoke');
export const smokeProjectTemplate = path.join(root, 'test/QueryBuilder.Tests.dproj');
export async function generateSmokeProjects() {
  const files = new Map();
  // Reuse the IDE-tested console project's complete configuration/inheritance
  // structure, instead of maintaining a reduced, MSBuild-only approximation.
  const projectTemplate = await readFile(smokeProjectTemplate, 'utf8');
  for (const [dialect, outputDialect] of Object.entries(smokeDialects)) {
    const imports = new Set(['System.SysUtils', 'System.Rtti']);
    const functions = [];
    const calls = [];
    for (const fixture of smokeCases) {
      const sql = typeof fixture.sql === 'function' ? fixture.sql(dialect) : fixture.sql;
      const code = await convert(sql, dialect);
      const [uses, unitList] = code.match(/^uses\n([\s\S]*?);\n\n/);
      unitList.split(',').forEach(unit => imports.add(unit.trim()));
      functions.push(`// ${fixture.name}: ${sql}\n${code.slice(uses.length).replace('function BuildQuery:', `function Build${fixture.name}:`)}`);
      calls.push(`  S := Check('${fixture.name}', Build${fixture.name}, TSqlDialect.${outputDialect}, ${fixture.bindings});`);
      for (const [index, value] of (fixture.integerValues || []).entries()) {
        const isInt64 = BigInt(value) < -2147483648n || BigInt(value) > 2147483647n;
        calls.push(`  CheckInteger(S.Bindings[${index}], '${value}', ${isInt64 ? 'True' : 'False'});`);
      }
      for (const [index, value] of (fixture.decimalValues || []).entries()) {
        calls.push(`  CheckFloat(S.Bindings[${index}], '${value}');`);
      }
    }
    const name = `ConverterSmoke${dialect}`;
    // Stable project identity is required by the Delphi IDE, not just MSBuild.
    const id = createHash('sha256').update(name).digest('hex').slice(0, 32).toUpperCase();
    const projectGuid = `{${id.slice(0, 8)}-${id.slice(8, 12)}-${id.slice(12, 16)}-${id.slice(16, 20)}-${id.slice(20)}}`;
    files.set(`${name}.dpr`, `// Generated by website/generate-smoke.mjs. Do not edit.\nprogram ${name};\n\n{$APPTYPE CONSOLE}\n\nuses\n  ${[...imports].join(',\n  ')};\n\n${functions.join('\n')}
function Check(const Name: string; const Query: IQuery;
  Dialect: TSqlDialect; ExpectedBindings: Integer): ISqlResult;
begin
  Result := Query.Compile(Dialect);
  if Trim(Result.Sql) = '' then
    raise Exception.Create(Name + ': empty SQL');
  if Result.Bindings.Count <> ExpectedBindings then
    raise Exception.Create(Name + ': wrong binding count');
  Writeln(Name + ': compiled SQL and checked bindings');
end;

procedure CheckInteger(const Value: TValue; const Expected: string; IsInt64: Boolean);
begin
  if IsInt64 then
  begin
    if not Value.IsType<Int64> then
      raise Exception.Create('Expected Int64 binding');
    if IntToStr(Value.AsInt64) <> Expected then
      raise Exception.Create('Int64 value changed');
  end
  else
  begin
    if not Value.IsType<Integer> then
      raise Exception.Create('Expected Integer binding');
    if IntToStr(Value.AsInteger) <> Expected then
      raise Exception.Create('Integer value changed');
  end;
end;

procedure CheckFloat(const Value: TValue; const Expected: string);
var
  Actual, ExpectedValue: Extended;
begin
  // TValue has Double and Extended implicit conversions. Natural real literals
  // may select either, depending on compiler/platform; never Integer or BCD.
  if not (Value.IsType<Double> or Value.IsType<Extended>) then
    raise Exception.Create('Expected a Double or Extended floating-point binding');
  Actual := Value.AsExtended;
  ExpectedValue := StrToFloat(Expected, TFormatSettings.Invariant);
  if ExpectedValue = 0 then
  begin
    if Actual <> 0 then
      raise Exception.Create('Expected a zero floating-point value');
  end
  else if Abs(Actual / ExpectedValue - 1) > 1E-14 then
    raise Exception.Create('Floating-point value exceeds the comparison tolerance');
  Writeln('Floating-point binding: ' + Value.TypeInfo.Name);
end;

var
  S: ISqlResult;
begin
  try
${calls.join('\n')}
    Writeln('${dialect}: ${smokeCases.length} generated functions passed');
  except
    on E: Exception do
    begin
      Writeln(E.ClassName + ': ' + E.Message);
      Halt(1);
    end;
  end;
end.
`);
    let project = projectTemplate
      .replace(/<ProjectGuid>[^<]+<\/ProjectGuid>/, `<ProjectGuid>${projectGuid}</ProjectGuid>`)
      .replaceAll('QueryBuilder.Tests', name)
      .replaceAll('QueryBuilder_Tests', name)
      .replace(/<DCC_UnitSearchPath>[^<]*<\/DCC_UnitSearchPath>/, '<DCC_UnitSearchPath>..\\..\\src;$(DCC_UnitSearchPath)</DCC_UnitSearchPath>')
      .replace(/<DCC_IncludePath>[^<]*<\/DCC_IncludePath>/, '<DCC_IncludePath>..\\..\\src;$(DCC_IncludePath)</DCC_IncludePath>')
      .replace(/<DCC_ExeOutput>[^<]*<\/DCC_ExeOutput>/, '<DCC_ExeOutput>.\\$(Platform)</DCC_ExeOutput>')
      .replace(/<DCC_DcuOutput>[^<]*<\/DCC_DcuOutput>/, '<DCC_DcuOutput>.\\$(Platform)\\dcu</DCC_DcuOutput>')
      .replace(/^.*<DCCReference\b[^\r\n]*\r?\n/gm, '');
    // MSBuild evaluates unconditional compiler options, but the IDE reads them
    // from configuration groups when resolving the executable to launch.
    const compilerOptions = [...project.matchAll(/^.*<DCC_[^\r\n]*\r?\n/gm)].map(match => match[0]).join('');
    project = project.replace(/^.*<DCC_[^\r\n]*\r?\n/gm, '')
      .replace(/(<SanitizedProjectName>[^<]+<\/SanitizedProjectName>\r?\n)/, `$1${compilerOptions}`);
    files.set(`${name}.dproj`, project);
  }
  // These are Windows Delphi IDE artifacts. Avoid IDE line-ending conversion
  // prompts and keep regeneration/checks identical on Windows and CI.
  return new Map([...files].map(([name, source]) => [name, source.replace(/\r?\n/g, '\r\n')]));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const checkOnly = process.argv.includes('--check');
  const files = await generateSmokeProjects();
  if (!checkOnly) await mkdir(smokeOutput, { recursive: true });
  for (const [name, source] of files) {
    const file = path.join(smokeOutput, name);
    const current = await readFile(file, 'utf8').catch(() => null);
    if (current === source) continue;
    if (checkOnly) throw new Error(`Stale or missing fixture: ${file}. Run npm run smoke:generate and rebuild in Delphi.`);
    await writeFile(file, source);
  }
  console.log(`${checkOnly ? 'Verified' : 'Generated'} ${Object.keys(smokeDialects).length} Delphi smoke projects (${smokeCases.length} functions each) in ${smokeOutput}`);
}
